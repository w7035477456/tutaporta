-- SMS appointment reminders for Bill Schedule (Monthly / Yearly) rows and ToDo tasks.
--
-- One sms_reminder row per reminder. The bill / todo row points at it through its own
-- sms_reminder_id column, so the link survives full-replace saves and the monthly / yearly
-- carry-forward copies (a copied Monthly row keeps reminding every month).
-- The 9am job (be/utils/smsReminder.js) reads the due date from the live bill / todo row.
--
-- The server also creates all of this on startup (initSmsReminderSchema), so running this
-- file by hand is optional.
--
-- Run (Mac):
--   psql -h 127.0.0.1 -p 50010 -U test_user1 -d outdatedDBOct2021 -f be/db/addSmsReminder.sql
-- Ubuntu Primary (from Mac):
--   scripts/ubuntu-psql.sh -f be/db/addSmsReminder.sql

CREATE TABLE IF NOT EXISTS outdateddbsnapshotoct2024.sms_reminder (
  sms_reminder_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  singles_id         bigint NOT NULL,
  kind               text   NOT NULL CHECK (kind IN ('monthly', 'yearly', 'todo')),
  phone              text   NOT NULL,
  days_before        integer NOT NULL DEFAULT 1 CHECK (days_before BETWEEN 0 AND 30),
  last_sent_due_date date NULL,
  last_sent_at       timestamptz NULL,
  last_error         text NULL,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS sms_reminder_singles_idx
  ON outdateddbsnapshotoct2024.sms_reminder (singles_id, updated_at DESC);

ALTER TABLE outdateddbsnapshotoct2024.monthly_bill
  ADD COLUMN IF NOT EXISTS sms_reminder_id bigint NULL;
ALTER TABLE outdateddbsnapshotoct2024.yearly_bill
  ADD COLUMN IF NOT EXISTS sms_reminder_id bigint NULL;
ALTER TABLE outdateddbsnapshotoct2024.todo_item
  ADD COLUMN IF NOT EXISTS sms_reminder_id bigint NULL;

CREATE INDEX IF NOT EXISTS monthly_bill_sms_reminder_idx
  ON outdateddbsnapshotoct2024.monthly_bill (sms_reminder_id) WHERE sms_reminder_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS yearly_bill_sms_reminder_idx
  ON outdateddbsnapshotoct2024.yearly_bill (sms_reminder_id) WHERE sms_reminder_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS todo_item_sms_reminder_idx
  ON outdateddbsnapshotoct2024.todo_item (sms_reminder_id) WHERE sms_reminder_id IS NOT NULL;
