export function normalizeUsPhoneDigits(raw) {
  const digits = String(raw ?? '').replace(/\D/g, '');
  if (digits.length === 11 && digits.startsWith('1')) return digits.slice(1);
  return digits;
}

export function isValidUsAreaCode(areaCode) {
  const code = String(areaCode ?? '').replace(/\D/g, '');
  if (code.length !== 3) return false;
  return VALID_US_AREA_CODES.has(code);
}

export function validateUsSignupPhone(raw) {
  const digits = normalizeUsPhoneDigits(raw);
  if (digits.length !== 10) {
    return { valid: false, digits };
  }
  const areaCode = digits.slice(0, 3);
  if (!isValidUsAreaCode(areaCode)) {
    return { valid: false, digits, areaCode };
  }
  return { valid: true, digits, areaCode, lineNumber: digits.slice(3) };
}

export function getUsSignupPhoneValidationMessage(raw) {
  const digits = normalizeUsPhoneDigits(raw);
  if (digits.length === 0) return 'Phone number is required.';
  if (digits.length >= 3 && !isValidUsAreaCode(digits.slice(0, 3))) {
    return 'Please enter a valid US area code.';
  }
  if (digits.length < 10) {
    return 'Please enter the 7-digit phone number after the area code.';
  }
  if (!isValidUsAreaCode(digits.slice(0, 3))) {
    return 'Please enter a valid US area code.';
  }
  return '';
}
