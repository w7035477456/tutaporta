/**
 * SMS appointment reminders (Bill Schedule Monthly / Yearly rows and ToDo tasks).
 *
 * - A bill / todo row links to one sms_reminder row via its sms_reminder_id column.
 * - Hourly check; from SMS_REMINDER_AT (local hour, default 9) on, texts every reminder whose
 *   send day (due date − days_before) is today or already passed while the due date has not.
 *   last_sent_due_date stops a second text for the same due date (also across restarts and
 *   PM2 cluster workers: the claim is one atomic UPDATE).
 * - Skipped: soft-deleted rows, Paid / Paid Off bills, tasks in Todo Done.
 * - Texts are plain ASCII (GSM-7) and kept under 160 characters = 1 Twilio segment.
 *
 * Env (~/.ssh/be/.env):
 *   SMS_REMINDER=true      — master switch for the hourly job (default true)
 *   SMS_REMINDER_AT=9      — hour 0–23 (default 9) in SMS_REMINDER_TZ
 *   SMS_REMINDER_TZ=America/New_York — clock used for "9am" and "today" (Ubuntu runs in UTC)
 *   plus Twilio vars, see lib/twilioSms.js
 */
import pool from '../db/connection.js';
import { isTwilioOptOutError, sendTwilioSms } from '../lib/twilioSms.js';

const LOG = '[sms-reminder]';
const S = 'outdateddbsnapshotoct2024';
const CHECK_EVERY_MS = 60 * 60 * 1000;
export const SMS_OPT_OUT = 'Reply STOP to opt out.';

let timer = null;
let runInFlight = null;

// ---------- schema ----------

export async function initSmsReminderSchema() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS ${S}.sms_reminder (
      sms_reminder_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      singles_id         bigint NOT NULL,
      kind               text   NOT NULL CHECK (kind IN ('monthly', 'yearly', 'todo')),
      phone              text   NOT NULL,
      days_before        integer NOT NULL DEFAULT 1 CHECK (days_before BETWEEN 0 AND 30),
      last_sent_due_date date NULL,
      last_sent_at       timestamptz NULL,
      last_error         text NULL,
      created_at         timestamptz NOT NULL DEFAULT now(),
      updated_at         timestamptz NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS sms_reminder_singles_idx ON ${S}.sms_reminder (singles_id, updated_at DESC);
    ALTER TABLE ${S}.monthly_bill ADD COLUMN IF NOT EXISTS sms_reminder_id bigint NULL;
    ALTER TABLE ${S}.yearly_bill  ADD COLUMN IF NOT EXISTS sms_reminder_id bigint NULL;
    ALTER TABLE ${S}.todo_item    ADD COLUMN IF NOT EXISTS sms_reminder_id bigint NULL;
    CREATE INDEX IF NOT EXISTS monthly_bill_sms_reminder_idx ON ${S}.monthly_bill (sms_reminder_id) WHERE sms_reminder_id IS NOT NULL;
    CREATE INDEX IF NOT EXISTS yearly_bill_sms_reminder_idx  ON ${S}.yearly_bill  (sms_reminder_id) WHERE sms_reminder_id IS NOT NULL;
    CREATE INDEX IF NOT EXISTS todo_item_sms_reminder_idx    ON ${S}.todo_item    (sms_reminder_id) WHERE sms_reminder_id IS NOT NULL;
  `);
}

// ---------- text ----------

/** First 3 words of the description, GSM-7 safe, "..." when cut. */
export function shortLabel(raw) {
  const plain = String(raw ?? '')
    .replace(/<[^>]*>/g, ' ')
    .replace(/[‘’]/g, "'")
    .replace(/[“”"]/g, '')
    .replace(/[^A-Za-z0-9 .,'&()/#:+-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (!plain) return 'your item';
  const words = plain.split(' ');
  let out = words.slice(0, 3).join(' ');
  if (out.length > 40) out = out.slice(0, 40).trim();
  return words.length > 3 || out.length < plain.length ? `${out}...` : out;
}

/** 'YYYY-MM-DD' → 'MM/DD/YYYY'. */
export function formatUsDate(ymd) {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(ymd ?? ''));
  return m ? `${m[2]}/${m[3]}/${m[1]}` : '';
}

function daysPhrase(days) {
  const n = Number(days) || 0;
  if (n === 0) return 'on the due date';
  return n === 1 ? '1 day before' : `${n} days before`;
}

/** Sent right after the user saves the popup. */
export function buildConfirmText({ label, dueYmd, daysBefore }) {
  const due = formatUsDate(dueYmd);
  const what = due ? `${shortLabel(label)} due ${due}` : shortLabel(label);
  return `TutaNotes: Reminder set for ${what}. We'll text you ${daysPhrase(daysBefore)}. ${SMS_OPT_OUT}`;
}

/** Sent at 9am on the reminder day. */
export function buildReminderText({ label, dueYmd }) {
  return `TutaNotes reminder: ${shortLabel(label)} is due ${formatUsDate(dueYmd)}. ${SMS_OPT_OUT}`;
}

// ---------- dates ----------

function ymd(d) {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

function dateOn(year, month, day) {
  const dim = new Date(year, month, 0).getDate();
  return new Date(year, month - 1, Math.min(Math.max(1, day), dim));
}

function parseYmd(value) {
  if (value instanceof Date) return new Date(value.getFullYear(), value.getMonth(), value.getDate());
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(value ?? ''));
  return m ? new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3])) : null;
}

/** Every due date a row stands for (Yearly rows with a Monthly period fall due each month). */
export function dueDatesForRow(kind, row) {
  if (kind === 'todo') {
    const d = parseYmd(row.due_date);
    return d ? [d] : [];
  }
  const year = Number(row.bill_year);
  if (kind === 'monthly') {
    const day = Number(row.due_day);
    if (!year || !(day >= 1 && day <= 31)) return [];
    return [dateOn(year, Number(row.bill_month), day)];
  }
  const day = Number(row.due_month_day);
  if (!year || !(day >= 1 && day <= 31)) return [];
  const period = String(row.bill_period || '').trim();
  if (period === 'Monthly') {
    return Array.from({ length: 12 }, (_, i) => dateOn(year, i + 1, day));
  }
  const month = Number(row.bill_month);
  if (!(month >= 1 && month <= 12)) return [];
  const dueYear = period === '2Year' ? Number(row.due_year) || year : year;
  return [dateOn(dueYear, month, day)];
}

/** Due date whose reminder window (send day … due day) contains `today`, else null. */
export function dueDateToRemind(kind, row, daysBefore, today = new Date()) {
  const t = new Date(today.getFullYear(), today.getMonth(), today.getDate()).getTime();
  for (const due of dueDatesForRow(kind, row)) {
    const send = new Date(due);
    send.setDate(send.getDate() - (Number(daysBefore) || 0));
    if (send.getTime() <= t && t <= due.getTime()) return due;
  }
  return null;
}

/** Next due date on/after today (for the confirmation text). */
export function nextDueYmd(kind, row, today = new Date()) {
  const t = new Date(today.getFullYear(), today.getMonth(), today.getDate()).getTime();
  const all = dueDatesForRow(kind, row);
  const upcoming = all.find((d) => d.getTime() >= t);
  const pick = upcoming || all[all.length - 1];
  return pick ? ymd(pick) : null;
}

// ---------- job ----------

function envFlag(name, defaultTrue) {
  const raw = String(process.env[name] ?? '').trim().toLowerCase();
  if (!raw) return defaultTrue;
  return ['1', 'true', 'yes', 'on'].includes(raw);
}

export function getSmsReminderTz() {
  return String(process.env.SMS_REMINDER_TZ ?? '').trim() || 'America/New_York';
}

/** Wall-clock time in SMS_REMINDER_TZ as a plain local Date (only y/m/d/h are used). */
export function nowInReminderTz(at = new Date()) {
  try {
    const parts = Object.fromEntries(
      new Intl.DateTimeFormat('en-US', {
        timeZone: getSmsReminderTz(),
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        hourCycle: 'h23'
      })
        .formatToParts(at)
        .map((p) => [p.type, p.value])
    );
    return new Date(Number(parts.year), Number(parts.month) - 1, Number(parts.day), Number(parts.hour));
  } catch {
    return at;
  }
}

export function getSmsReminderAtHour() {
  const n = Number(String(process.env.SMS_REMINDER_AT ?? '9').trim());
  return Number.isFinite(n) && n >= 0 && n <= 23 ? Math.trunc(n) : 9;
}

async function loadCandidates(client) {
  // One connection → run the three queries one after another (pg does not queue them in parallel).
  const monthly = await client.query(
      `SELECT r.sms_reminder_id, r.phone, r.days_before, r.last_sent_due_date,
              mb.bill_year, mb.bill_month, mb.due_day, mb.bill_description AS label
         FROM ${S}.sms_reminder r
         JOIN ${S}.monthly_bill mb ON mb.sms_reminder_id = r.sms_reminder_id AND mb.singles_id = r.singles_id
        WHERE r.kind = 'monthly' AND mb.soft_delete = false
          AND mb.action IS DISTINCT FROM 'Paid' AND mb.bill_type IS DISTINCT FROM 'Paid Off'`
  );
  const yearly = await client.query(
      `SELECT r.sms_reminder_id, r.phone, r.days_before, r.last_sent_due_date,
              yb.bill_year, yb.bill_month, yb.due_month_day, yb.due_year, yb.bill_period,
              yb.bill_description AS label
         FROM ${S}.sms_reminder r
         JOIN ${S}.yearly_bill yb ON yb.sms_reminder_id = r.sms_reminder_id AND yb.singles_id = r.singles_id
        WHERE r.kind = 'yearly' AND yb.soft_delete = false
          AND yb.action IS DISTINCT FROM 'Paid'`
  );
  const todo = await client.query(
      `SELECT r.sms_reminder_id, r.phone, r.days_before, r.last_sent_due_date,
              to_char(t.due_date, 'YYYY-MM-DD') AS due_date, t.body AS label
         FROM ${S}.sms_reminder r
         JOIN ${S}.todo_item t ON t.sms_reminder_id = r.sms_reminder_id AND t.singles_id = r.singles_id
        WHERE r.kind = 'todo' AND t.lane <> 'done' AND t.kind IS DISTINCT FROM 'divider'
          AND t.due_date IS NOT NULL`
  );
  return [
    ...monthly.rows.map((r) => ({ kind: 'monthly', row: r })),
    ...yearly.rows.map((r) => ({ kind: 'yearly', row: r })),
    ...todo.rows.map((r) => ({ kind: 'todo', row: r }))
  ];
}

export async function runSmsReminders(now = nowInReminderTz()) {
  const client = await pool.connect();
  let sent = 0;
  let failed = 0;
  try {
    const candidates = await loadCandidates(client);
    for (const { kind, row } of candidates) {
      const due = dueDateToRemind(kind, row, row.days_before, now);
      if (!due) continue;
      const dueYmd = ymd(due);
      // Atomic claim: only one worker / run texts this due date.
      const { rowCount } = await client.query(
        `UPDATE ${S}.sms_reminder
            SET last_sent_due_date = $2::date, last_sent_at = now(), last_error = NULL, updated_at = now()
          WHERE sms_reminder_id = $1
            AND last_sent_due_date IS DISTINCT FROM $2::date`,
        [row.sms_reminder_id, dueYmd]
      );
      if (!rowCount) continue;
      try {
        await sendTwilioSms(row.phone, buildReminderText({ label: row.label, dueYmd }));
        sent += 1;
      } catch (err) {
        failed += 1;
        const optedOut = isTwilioOptOutError(err);
        // Opted out: keep the claim (do not retry). Other errors: release so the next hourly check retries.
        await client.query(
          `UPDATE ${S}.sms_reminder
              SET last_error = $2,
                  last_sent_due_date = CASE WHEN $3 THEN last_sent_due_date ELSE NULL END,
                  updated_at = now()
            WHERE sms_reminder_id = $1`,
          [row.sms_reminder_id, String(err?.message || err).slice(0, 500), optedOut]
        );
        console.error(`${LOG} send failed`, { id: row.sms_reminder_id, code: err?.code, message: err?.message });
      }
    }
  } finally {
    client.release();
  }
  if (sent || failed) console.log(`${LOG} run done: sent=${sent} failed=${failed}`);
  return { sent, failed };
}

async function tick() {
  if (nowInReminderTz().getHours() < getSmsReminderAtHour()) return;
  if (runInFlight) return;
  runInFlight = runSmsReminders()
    .catch((err) => console.error(`${LOG} run failed:`, err?.message ?? err))
    .finally(() => {
      runInFlight = null;
    });
  await runInFlight;
}

export function startSmsReminderJob() {
  if (!envFlag('SMS_REMINDER', true)) {
    console.log(`${LOG} job off (SMS_REMINDER=false)`);
    return;
  }
  if (timer) clearInterval(timer);
  timer = setInterval(() => void tick(), CHECK_EVERY_MS);
  timer.unref?.();
  // First check shortly after startup (catches up if the server was down at 9am).
  setTimeout(() => void tick(), 60 * 1000).unref?.();
  console.log(
    `${LOG} hourly check; texts go out from SMS_REMINDER_AT=${getSmsReminderAtHour()} ${getSmsReminderTz()}`
  );
}
